def plot_q2_xbj(data):
    mask = data["isCC"] == 1
    q2 = data["Q2"][mask]
    xbj = data["xBj"][mask]
    valid = np.isfinite(q2) & np.isfinite(xbj) & (q2 > 0) & (xbj > 0)
    q2 = q2[valid]
    xbj = xbj[valid]

    if q2.size == 0:
        print("No valid CC kinematic points available for Q2/xBj plot.")
        return

    fig, ax = plt.subplots(figsize=(7, 6))
    h = ax.hist2d(xbj, q2 / 1e6, bins=50, cmap="viridis", normed=False)
    fig.colorbar(h[3], ax=ax, label="Event count")
    ax.set_xlabel("xBj")
    ax.set_ylabel("Q^2 [GeV^2]")
    ax.set_title("Q^2 vs xBj for CC Events")
    ax.set_xscale("log")
    ax.set_yscale("log")
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "q2_xbj.png"))
    plt.close(fig)
    print(SENTENCES["q2_xbj"])


