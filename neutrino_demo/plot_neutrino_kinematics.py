def load_tree(filename=ROOT_FILE, tree_name=TREE_NAME):
    with uproot.open(filename) as f:
        tree = f[tree_name]
        data = tree.arrays(library="np")
    return data


def plot_cc_vs_nc(data):
    values = np.zeros(2, dtype=int)
    values[0] = np.count_nonzero(data["isCC"])
    values[1] = np.count_nonzero(data["isNC"])
    labels = ["CC", "NC"]

    fig, ax = plt.subplots(figsize=(6, 5))
    ax.bar(labels, values, color=["#1f77b4", "#ff7f0e"])
    ax.set_ylabel("Event count")
    ax.set_title("Charged Current vs Neutral Current")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "cc_vs_nc.png"))
    plt.close(fig)
    print(SENTENCES["cc_vs_nc"])


def plot_nu_interaction_process(data):
    proc = data.get("nuInteractionProcess")
    if proc is None or len(proc) == 0:
        return

    mask = np.array([(p is not None) and str(p).strip() not in ["", "None"] for p in proc])
    proc = proc[mask]
    if proc.size == 0:
        return

    names, counts = np.unique(proc, return_counts=True)
    order = np.argsort(counts)[::-1]
    names = names[order]
    counts = counts[order]
    n_events = proc.size
    rates = counts / n_events

    print("\nPrimary neutrino interaction rates per interacting event:")
    for name, rate in zip(names, rates):
        print(f"{name:25s}  {rate:.4e}")

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.bar(names, rates, color="#7f7f7f", edgecolor="black")
    ax.set_ylabel("Interactions per event")
    ax.set_title("Primary Neutrino Interaction Processes per Event")
    ax.set_xticklabels(names, rotation=45, ha="right")
    ax.grid(axis="y", alpha=0.3)
    ax.set_yscale("log")
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "nu_interaction_process.png"))
    plt.close(fig)
    print(SENTENCES["nu_interaction_process"])


def plot_interaction_model(data):
    labels = ["QE", "RES", "DIS", "Other", "Unknown"]
    counts = [0] * len(labels)
    model = data.get("interactionModel")
    if model is None:
        return
    for i, label in enumerate(labels):
        counts[i] = np.count_nonzero(model == label)

    fig, ax = plt.subplots(figsize=(7, 5))
    ax.bar(labels, counts, color=["#2ca02c", "#d62728", "#9467bd", "#8c564b", "#7f7f7f"])
    ax.set_ylabel("Event count")
    ax.set_title("Interaction Model Breakdown")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "interaction_model.png"))
    plt.close(fig)
    print(SENTENCES["interaction_model"])


