def plot_secondary_creator_process(data):
    creator = data.get("step_creatorproc")
    if creator is None or len(creator) == 0:
        return

    event_counts = {}
    n_events = len(creator)
    for row in creator:
        counts = {}
        for item in row:
            if item and item != "Primary":
                counts[item] = counts.get(item, 0) + 1
        for item, cnt in counts.items():
            event_counts[item] = event_counts.get(item, 0) + cnt

    if len(event_counts) == 0:
        return

    names = []
    avg_per_event = []
    for item, total in sorted(event_counts.items(), key=lambda kv: -kv[1]):
        names.append(item)
        avg_per_event.append(total / n_events)

    print("\nSecondary creator process rates per event:")
    for name, rate in zip(names, avg_per_event):
        print(f"{name:25s}  {rate:.4e}")

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.bar(names, avg_per_event, color="#9467bd", edgecolor="black")
    ax.set_ylabel("Average count per event")
    ax.set_title("Secondary Creator Process Count per Event")
    ax.set_xticklabels(names, rotation=45, ha="right")
    ax.grid(axis="y", alpha=0.3)
    ax.set_yscale("log")
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "secondary_creator_process.png"))
    plt.close(fig)
    print(SENTENCES["secondary_creator_process"])


def plot_hadronic_multiplicity(data):
    nprotons = data.get("nProtonSec", np.zeros(0, dtype=int))
    nneutrons = data.get("nNeutron", np.zeros(0, dtype=int))
    npions = data.get("nPionPlus", np.zeros(0, dtype=int)) + data.get("nPionMinus", np.zeros(0, dtype=int)) + data.get("nPionZero", np.zeros(0, dtype=int))
    if len(nprotons) == 0 or len(nneutrons) == 0:
        return
    hadronic_count = nprotons + nneutrons + npions

    fig, ax = plt.subplots(figsize=(7, 5))
    ax.hist(hadronic_count, bins=np.arange(hadronic_count.min(), hadronic_count.max() + 2) - 0.5, color="#2ca02c", edgecolor="black")
    ax.set_xlabel("Hadronic secondary count (p+n+\pi)")
    ax.set_ylabel("Event count")
    ax.set_title("Hadronic Multiplicity")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(PLOT_DIR, "hadronic_multiplicity.png"))
    plt.close(fig)
    print(SENTENCES["hadronic_multiplicity"])


